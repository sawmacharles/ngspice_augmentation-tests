class CouldNotRun(Exception):
    pass


def run_ngspice(deck_path, timeout=900, env=None):
    t0 = time.time()
    try:
        proc = subprocess.run([NGSPICE_AUG, "-b", deck_path], capture_output=True,
                               text=True, timeout=timeout, cwd=os.path.dirname(deck_path),
                               env=env)
    except FileNotFoundError as e:
        raise CouldNotRun(f"cannot start {NGSPICE_AUG}: {e}")
    except subprocess.TimeoutExpired:
        raise CouldNotRun(f"{deck_path} timed out after {timeout}s")
    return proc.returncode, proc.stdout + proc.stderr, time.time() - t0


def read_wrdata_complex(path, ncols):
    if not os.path.exists(path):
        raise CouldNotRun(f"ngspice wrote no {path}")
    freqs, cols = [], [[] for _ in range(ncols)]
    with open(path) as fh:
        next(fh, None)
        for row in fh:
            v = row.split()
            if not v:
                continue
            v = [float(x) for x in v]
            if len(v) != 1 + 2 * ncols:
                raise CouldNotRun(f"unexpected column count in {path}: {row!r}")
            freqs.append(v[0])
            for k in range(ncols):
                cols[k].append(complex(v[1 + 2 * k], v[2 + 2 * k]))
    if not freqs:
        raise CouldNotRun(f"{path} is empty")
    return freqs, cols


def read_fra_csv(path):
    """(freq, db, deg) list from a tools/fra.py-style fra.csv (loop or
    transfer mode -- both share freq,status,...,*_db,*_phase_deg columns;
    loop mode's own combined_db/combined_phase_deg are used since that is
    the FRA reference this project's other checks (test_pac.py) already
    compare .pstb against)."""
    if not os.path.exists(path):
        raise CouldNotRun(f"no FRA reference at {path}")
    rows = []
    with open(path) as fh:
        header = fh.readline().strip().split(",")
        idx = {name: i for i, name in enumerate(header)}
        db_key = "combined_db" if "combined_db" in idx else "H_db"
        deg_key = "combined_phase_deg" if "combined_phase_deg" in idx else "H_phase_deg"
        for line in fh:
            v = line.strip().split(",")
            if len(v) < len(header) or v[1] != "ok":
                continue
            f = float(v[idx["freq"]])
            db = float(v[idx[db_key]])
            deg = float(v[idx[deg_key]])
            rows.append((f, db, deg))
    if not rows:
        raise CouldNotRun(f"{path}: no 'ok' rows")
    return rows


PAC_NEAR_FS2_HZ = {199054, 199053.59, 199054.0}


def compare_vs_fra(name, mine, ref, near_fs2=PAC_NEAR_FS2_HZ):
    """Report EVERY point (never excluded), 0.5dB/3deg target, flagging
    which points are near fs/2 (per the task: do not exclude, but note)."""
    if len(mine) != len(ref):
        raise CouldNotRun(f"{name}: point count mismatch: mine {len(mine)}, ref {len(ref)}")
    lines = []
    worst_db, worst_ph = 0.0, 0.0
    n_near_fail = 0
    n_far_fail = 0
    for (fm, dbm, degm), (fr, dbr, degr) in zip(mine, ref):
        if abs(fm - fr) > 2e-3 * fr:
            raise CouldNotRun(f"{name}: frequency mismatch {fm} vs {fr}")
        ddb = abs(dbm - dbr)
        dph = abs(degm - degr)
        while dph > 180.0:
            dph = abs(dph - 360.0)
        is_near = any(abs(fr - z) < 1.0 for z in near_fs2) or fr > 0.75 * 250000.0
        ok = ddb <= 0.5 and dph <= 3.0
        if not ok:
            if is_near:
                n_near_fail += 1
            else:
                n_far_fail += 1
        worst_db = max(worst_db, ddb)
        worst_ph = max(worst_ph, dph)
        lines.append(f"    {fr:>10.4g} Hz  dB(mine={dbm:8.3f} ref={dbr:8.3f} "
                      f"diff={ddb:6.3f}) deg(mine={degm:8.3f} ref={degr:8.3f} diff={dph:6.3f})"
                      f"{'  [near fs/2]' if is_near else ''}{'  MISS' if not ok else ''}")
    detail = (f"{len(mine)} points, worst |H| err {worst_db:.3f}dB worst phase err {worst_ph:.3f}deg "
              f"(target 0.5dB/3deg); misses: {n_far_fail} away from fs/2, {n_near_fail} near fs/2\n"
              + "\n".join(lines))
    ok_all = (n_far_fail == 0 and n_near_fail == 0)
    return ok_all, detail


