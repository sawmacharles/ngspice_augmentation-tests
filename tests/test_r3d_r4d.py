def check_vs_baseline(tag, deck_dir, base_table, base_pm_deg, base_pm_freq):
    name = f"{tag}: R{'3' if '3' in tag else '4'}d vs R{'3' if '3' in tag else '4'} loop-gain (crossover/PM/curve shape)"
    try:
        summ_path = os.path.join(FRA_ROOT, deck_dir, "summary.json")
        csv_path = os.path.join(FRA_ROOT, deck_dir, "fra.csv")
        if not (os.path.exists(summ_path) and os.path.exists(csv_path)):
            raise CouldNotRun(f"missing {summ_path} or {csv_path}")
        with open(summ_path) as fh:
            summ = json.load(fh)
        rd_curve = read_fra_csv(csv_path)
        pm = (summ.get("combined_margins") or {}).get("pm")
        pm_deg = pm["pm_deg"] if pm else None
        pm_freq = pm["freq"] if pm else None
        deltas = []
        for (fr, dbr, degr), (fb, dbb, degb) in zip(rd_curve, base_table):
            if abs(fr - fb) > 2e-3 * fb:
                raise CouldNotRun(f"grid mismatch {fr} vs {fb}")
            deltas.append((fr, dbr - dbb, degr - degb))
        max_ddb = max(abs(d[1]) for d in deltas)
        max_ddeg = max(abs(d[2]) for d in deltas)
        pm_diff = (pm_deg - base_pm_deg) if pm_deg is not None else None
        freq_diff_pct = (100.0 * (pm_freq - base_pm_freq) / base_pm_freq) if pm_freq else None
        lines = "\n".join(f"    {f:>10.4g} Hz  dB diff {ddb:+7.3f}  deg diff {ddeg:+7.3f}"
                           for f, ddb, ddeg in deltas)
        detail = (f"crossover(PM freq): rd={pm_freq} base={base_pm_freq} ({freq_diff_pct:+.2f}% )"
                   if pm_freq else "crossover: n/a") + \
                  f"; PM: rd={pm_deg} base={base_pm_deg}deg (diff {pm_diff:+.3f}deg)\n" \
                  f"    max |dB diff|={max_ddb:.3f} max |deg diff|={max_ddeg:.3f}\n{lines}"
        record(name, "info", detail)
    except CouldNotRun as e:
        record(name, "COULD-NOT-RUN", str(e))
    except Exception as e:  # noqa: BLE001
        record(name, "COULD-NOT-RUN", f"{type(e).__name__}: {e}")


