CONVERGED_RE = re.compile(
    r"PSS-SHOOT: CONVERGED iter=(\d+) residual=([\d.eE+-]+) "
    r"spectral_radius=([\d.eE+-]+) (\S+) wall_time=([\d.eE+-]+)s")


def parse_shoot(out):
    m = CONVERGED_RE.search(out)
    if not m:
        return None
    return {"iter": int(m.group(1)), "residual": float(m.group(2)),
            "specrad": float(m.group(3)), "stability": m.group(4),
            "wall_time": float(m.group(5))}


def _read_wrdata_pair(path, signal_index):
    times, vals = [], []
    c0, c1 = 2 * signal_index, 2 * signal_index + 1
    with open(path) as f:
        for line in f:
            p = line.split()
            if len(p) > c1:
                try:
                    t = float(p[c0]); v = float(p[c1])
                except ValueError:
                    continue
                times.append(t)
                vals.append(v)
    return times, vals


def _interp(times, vals, t):
    import bisect
    if t <= times[0]:
        return vals[0]
    if t >= times[-1]:
        return vals[-1]
    i = bisect.bisect_right(times, t) - 1
    if i >= len(times) - 1:
        return vals[-1]
    t0, t1 = times[i], times[i + 1]
    v0, v1 = vals[i], vals[i + 1]
    return v0 if t1 == t0 else v0 + (t - t0) / (t1 - t0) * (v1 - v0)


def _phase_samples(times, vals, period, n_phases, t_start):
    return [_interp(times, vals, t_start + k * period / n_phases) for k in range(n_phases)]


