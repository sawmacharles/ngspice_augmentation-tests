def check_pss_deck(tag, cfg):
    name = f"{tag}: PSS-SHOOT convergence + Floquet"
    # card #550: the fixtures write their wrdata to these absolute paths and ngspice does not create directories; they exist on
    # the development workstation (AMD Ryzen AI Max+ 395, Linux) from older runs, a fresh machine (a second workstation) has none, and the equal-tolerance check below then reported COULD-NOT-RUN.
    # The files are produced by this very test (shoot fixture, settled-tran fixture), nothing needs syncing.
    for _p in (cfg["shoot_txt"], cfg["tight_txt"]):
        os.makedirs(os.path.dirname(_p), exist_ok=True)
    shoot_deck = os.path.join(FIXTURES, cfg["shoot"])
    if not os.path.exists(shoot_deck):
        record(name, "COULD-NOT-RUN", f"missing fixture {shoot_deck}")
        return
    try:
        rc, out, wall = run_ngspice(shoot_deck, timeout=300)
    except CouldNotRun as e:
        record(name, "COULD-NOT-RUN", str(e))
        return
    got = parse_shoot(out)
    if got is None:
        record(name, "FAIL", f"exit {rc}, no CONVERGED line; tail: {out[-600:]}")
        return
    record(name, "pass" if got["residual"] <= 1e-6 and got["stability"] == "stable" else "FAIL",
           f"iter={got['iter']} residual={got['residual']:.3e} specrad={got['specrad']:.4f} "
           f"({got['stability']}) engine_wall={got['wall_time']:.3f}s harness_wall={wall:.3f}s")

    # orbit vs equal-tolerance settled .tran
    tight_deck = os.path.join(FIXTURES, cfg["tight"])
    if not os.path.exists(tight_deck):
        record(f"{tag}: orbit vs settled .tran (equal tolerance)", "COULD-NOT-RUN",
               f"missing fixture {tight_deck}")
    else:
        try:
            trc, tout, twall_tight = run_ngspice(tight_deck, timeout=1800)
        except CouldNotRun as e:
            record(f"{tag}: orbit vs settled .tran (equal tolerance)", "COULD-NOT-RUN", str(e))
            twall_tight = None
        else:
            shoot_txt = cfg["shoot_txt"]
            tight_txt = cfg["tight_txt"]
            if not (os.path.exists(shoot_txt) and os.path.exists(tight_txt)):
                record(f"{tag}: orbit vs settled .tran (equal tolerance)", "COULD-NOT-RUN",
                       f"missing {shoot_txt} or {tight_txt}")
            else:
                T = cfg["period"]
                tran_t_start = cfg["tight_tstop"] - T
                for sig_name, shoot_idx, tight_idx in cfg["checks"]:
                    cname = f"{tag}: {sig_name} orbit vs settled .tran (target <=0.1% of ripple, info if not met)"
                    st, sv = _read_wrdata_pair(shoot_txt, shoot_idx)
                    tt, tv = _read_wrdata_pair(tight_txt, tight_idx)
                    if not st or not tt:
                        record(cname, "COULD-NOT-RUN", "no data")
                        continue
                    ssamp = _phase_samples(st, sv, T, 20, st[0])
                    tsamp = _phase_samples(tt, tv, T, 20, tran_t_start)
                    rip = max(tsamp) - min(tsamp)
                    if rip <= 0.0:
                        # card #505: the settled .tran reference itself is degenerate (R3d: the
                        # op-amp's ps-scale positive-feedback pole makes a reltol<=1e-4 .tran
                        # from t=0 blow up, or the two-stage workaround land on the collapsed
                        # non-switching state -- vout=1.7e-7 V, opout=-1e5 V); not an engine
                        # result. docs/pss-pac.md "card #505".
                        record(cname, "COULD-NOT-RUN",
                               "settled .tran reference is degenerate (zero ripple over the last "
                               "period: collapsed/blown-up plain .tran, model defect, see docs/pss-pac.md "
                               "card #505); orbit accuracy for this deck is shown on the polarity-corrected "
                               "twin instead")
                        continue
                    diffs = [abs(a - b) for a, b in zip(ssamp, tsamp)]
                    maxdiff = max(diffs)
                    pct_max = 100.0 * maxdiff / rip if rip > 0 else float("inf")
                    ok = pct_max <= 0.1
                    if sig_name in cfg.get("default_tol_info", ()):
                        record(cname, "pass" if ok else "info",
                               f"ripple={rip:.6g} max_diff={maxdiff:.6g} ({pct_max:.4f}% of ripple) "
                               f"[info: shoot at default reltol=1e-3 vs reltol=1e-5 .tran; tolerance-limited, "
                               f"see the equal-tolerance check below and card #531]")
                        continue
                    # honest per test_pss.py precedent: some states (e.g. compensator-pole
                    # states) may legitimately miss this target even when the engine is
                    # working correctly (documented accuracy floor, tests/test_pss.py's
                    # own opout FAIL on R3) -- report the real number either way.
                    record(cname, "pass" if ok else "FAIL",
                           f"ripple={rip:.6g} max_diff={maxdiff:.6g} ({pct_max:.4f}% of ripple)")

    # card #531: equal-tolerance orbit check (shoot at reltol=R1, settled .tran at reltol=R2 < R1).
    if cfg.get("eq_tol"):
        check_orbit_equal_tol(tag, cfg)

    # speed vs the deck's OWN settled .tran (refs/, not the tight reference)
    try:
        trc2, tout2, twall = run_ngspice(cfg["tran_ref"], timeout=120)
        ratio = twall / wall if wall > 0 else float("inf")
        record(f"{tag}: shoot vs settled .tran wall time (info, target >=10x typically)",
               "pass" if ratio >= 10.0 else "info",
               f"settled .tran {twall:.3f}s, shoot harness {wall:.3f}s, ratio {ratio:.1f}x")
    except CouldNotRun as e:
        record(f"{tag}: settled .tran timing reference", "COULD-NOT-RUN", str(e))

    return got


def _variant_deck(src, outdir, tag, reltol, out_map):
    """Copy of fixture `src` with `.options reltol=<reltol>` (placed right before the analysis
    command, or replacing the fixture's own final reltol line), the stb include made absolute,
    the .raw `write` lines dropped, `save` limited to what wrdata needs (the unrestricted ascii
    .raw of a 6 ms reltol<=1e-6 run is several GB), and the wrdata paths remapped via out_map."""
    with open(src) as fh:
        text = fh.read()
    text = text.replace(".include ../../stb/lgprobe.lib",
                        f".include {os.path.join(ROOT, 'stb', 'lgprobe.lib')}")
    for a, b in out_map.items():
        text = text.replace(a, b)
    text = re.sub(r"(?m)^write .*\n", "", text)
    text = text.replace("set filetype=ascii", "save v(vout) i(L1) v(opout) v(vc) v(dly_hs) v(dly_ls)"
                        if re.search(r"(?m)^tran ", text) else "")
    if re.search(r"(?m)^\.options reltol=1e-5$", text):       # the tran fixture
        text = re.sub(r"(?m)^\.options reltol=1e-5$", f".options reltol={reltol}", text)
    else:                                                       # the shoot fixture
        text = re.sub(r"(?m)^(pss .*)$", f".options reltol={reltol}\n\\1", text, count=1)
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, f"{tag}.cir")
    with open(path, "w") as fh:
        fh.write(text)
    return path


def _tail_window(path, cfg):
    """card #549: rewrite the settled-tran deck so it writes only the last 25 us (the full 6/12 ms wrdata file is 0.8-1.6 GB; only the last period is read)."""
    txt = open(path).read()
    tstop = f"{cfg['tight_tstop'] * 1e3:g}m"
    txt, nsub = re.subn(r"(?m)^tran 2n " + tstop + r" 0( uic)?$",
                        lambda m: f"tran 2n {tstop} {cfg['tight_tstop'] - 25e-6:.9g}{m.group(1) or ''}", txt)
    if nsub != 1:
        raise CouldNotRun("tran line not found in the settled-tran fixture")
    open(path, "w").write(txt)


def check_orbit_equal_tol(tag, cfg):
    name = f"{tag}: orbit vs settled .tran at equal/finer tolerance"
    try:
        eq = cfg["eq_tol"]
        outdir = os.path.join(DATA_ROOT, "orbit_eqtol", tag)
        sh_txt = os.path.join(outdir, "shoot.txt")
        tr_txt = os.path.join(outdir, "tran.txt")
        sh = _variant_deck(os.path.join(FIXTURES, cfg["shoot"]), outdir, "shoot", eq["shoot_reltol"],
                           {cfg["shoot_txt"]: sh_txt})
        tr = _variant_deck(os.path.join(FIXTURES, cfg["tight"]), outdir, "tran", eq["tran_reltol"],
                           {cfg["tight_txt"]: tr_txt})
        _tail_window(tr, cfg)
        _, sh_out, _ = run_ngspice(sh, timeout=300)
        run_ngspice(tr, timeout=1800)
        T = cfg["period"]
        if parse_shoot(sh_out) is None:
            raise CouldNotRun("equal-tolerance shoot run did not converge")
        for sig_name, shoot_idx, tight_idx in cfg["checks"]:
            st, sv = _read_wrdata_pair(sh_txt, shoot_idx)
            tt, tv = _read_wrdata_pair(tr_txt, tight_idx)
            ssamp = _phase_samples(st, sv, T, 20, st[0])
            tsamp = _phase_samples(tt, tv, T, 20, cfg["tight_tstop"] - T)
            rip = max(tsamp) - min(tsamp)
            pct = 100.0 * max(abs(a - b) for a, b in zip(ssamp, tsamp)) / rip
            # card #549: bounds tightened per signal (measured 2026-10-02, s101 == 549: R3d vout 0.0042 / i(L1) 0.0036 / opout 0.0418 %, R4d vout
            # 0.0026 / i(L1) 0.0024 / vc 0.089 % of ripple; the compensator nodes are tolerance-limited: the reltol 1e-5 / 1e-6 / 1e-7 settled
            # trans differ from each other by 0.2 / 0.07 % (R4d vc) of its 1.3 mV ripple)
            lim = {"opout": 0.1, "vc": 0.15}.get(sig_name, 0.01)
            record(f"{tag}: {sig_name} orbit (shoot reltol={eq['shoot_reltol']}) vs settled .tran "
                   f"(reltol={eq['tran_reltol']}) (target <={lim}% of ripple)",
                   "pass" if pct <= lim else "FAIL", f"ripple={rip:.6g} max_diff={pct:.4f}% of ripple")
    except CouldNotRun as e:
        record(name, "COULD-NOT-RUN", str(e))


CHARGED_DIODE = ".model ddt D(IS=1e-6 N=1.0 CJO=1p TT=1n)"


def check_charged_diode(tag, cfg, red=False):
    """card #549: the dead-time network's discharge diode WITH charge (CJO=1p TT=1n; the shipped decks use IS only, a chargeless diode that carries no
    hidden state).  A diode with charge is a charge-carrying device like a MOSFET: the period restart of the shooting engine re-initialised its
    charge history, giving an orbit error of 3.2 % (R3d opout) / 0.11 % (R4d vc) of the node's ripple and 0.09 % / 0.002 % (vout) against the settled
    tran of finer tolerance (reltol 1e-6, last period of a 6 / 12 ms run); the hidden-state continuation of the restart (full node vector of the
    previous run, device ics re-derived) is the default for diodes with charge and gives 0.031 / 0.025 % (comp) and 0.004 / 0.0014 % (vout).
    Bounds: vout and i(L1) 0.01 %, compensator node 0.1 % of ripple.  Red proof PSS_NO_HIDDEN=1 must exceed the compensator bound (R3d 3.2 %).
    Chargeless-diode decks are NOT changed (bit-identical to s101): there the hidden-vector orbit is no better and the native .pac recording pass,
    which restarts from native states, then no longer closes the orbit (R4d line2out +0.24 dB), see docs/pss-pac.md card #549."""
    name = f"{tag}: charged-diode (CJO=1p TT=1n) orbit vs settled .tran, shoot reltol 1e-5 / tran 1e-6" + (" [RED PROOF: PSS_NO_HIDDEN=1, must exceed the bound]" if red else "")
    try:
        outdir = os.path.join(DATA_ROOT, "orbit_charged", tag + ("_red" if red else ""))
        sh_txt = os.path.join(outdir, "shoot.txt")
        tr_txt = os.path.join(outdir, "tran.txt")
        sh = _variant_deck(os.path.join(FIXTURES, cfg["shoot"]), outdir, "shoot", "1e-5", {cfg["shoot_txt"]: sh_txt})
        tr = _variant_deck(os.path.join(FIXTURES, cfg["tight"]), outdir, "tran", "1e-6", {cfg["tight_txt"]: tr_txt})
        for pth in (sh, tr):
            txt = open(pth).read()
            if "D(IS=1e-6 N=1.0)" not in txt:
                raise CouldNotRun(f"{pth}: discharge-diode model line not found")
            txt = txt.replace(".model ddt D(IS=1e-6 N=1.0)", CHARGED_DIODE)
            open(pth, "w").write(txt)
        _tail_window(tr, cfg)
        env = dict(os.environ)
        if red:
            env["PSS_NO_HIDDEN"] = "1"
        _, sh_out, _ = run_ngspice(sh, timeout=300, env=env)
        normal_tr = os.path.join(DATA_ROOT, "orbit_charged", tag, "tran.txt")
        if red and os.path.exists(normal_tr):   # the settled reference does not depend on the red-proof switch
            tr_txt = normal_tr
        else:
            run_ngspice(tr, timeout=1800)
        T = cfg["period"]
        if parse_shoot(sh_out) is None:
            raise CouldNotRun("charged-diode shoot run did not converge")
        worst, parts = {}, []
        for sig_name, shoot_idx, tight_idx in cfg["checks"]:
            st, sv = _read_wrdata_pair(sh_txt, shoot_idx)
            tt, tv = _read_wrdata_pair(tr_txt, tight_idx)
            ssamp = _phase_samples(st, sv, T, 20, st[0])
            tsamp = _phase_samples(tt, tv, T, 20, cfg["tight_tstop"] - T)
            rip = max(tsamp) - min(tsamp)
            pct = 100.0 * max(abs(a - b) for a, b in zip(ssamp, tsamp)) / rip
            lim = 0.1 if sig_name in ("opout", "vc") else 0.01
            worst[sig_name] = (pct, lim)
            parts.append(f"{sig_name} {pct:.4f}% (bound {lim})")
        ok = all(p <= l for p, l in worst.values())
        if red:
            comp = "opout" if "opout" in worst else "vc"
            record(name, "pass" if worst[comp][0] > worst[comp][1] else "FAIL", "; ".join(parts) + " of ripple (compensator node must exceed its bound)")
        else:
            record(name, "pass" if ok else "FAIL", "; ".join(parts) + " of ripple")
    except CouldNotRun as e:
        record(name, "COULD-NOT-RUN", str(e))


def check_pss_efficiency(tag, cfg):
    name = f"{tag}: PSS-orbit efficiency via tools/loss.py --pss vs .tran-window efficiency"
    outdir = os.path.join(DATA_ROOT, "loss_pss", tag)
    cmd = [sys.executable, LOSS_PY, cfg["tran_ref"], "--pss",
           "--fguess", str(cfg["fguess"]), "--stabtime", str(cfg["stabtime"]),
           "--oscnode", cfg["oscnode"], "--period", str(cfg["period"]),
           "--ngspice-aug", NGSPICE_AUG, "--out", outdir] + cfg["loss_args"]
    t0 = time.time()
    try:
        proc = subprocess.run(cmd, cwd=REFS, capture_output=True, text=True, timeout=600)
    except subprocess.TimeoutExpired:
        record(name, "COULD-NOT-RUN", "tools/loss.py --pss timed out after 600s")
        return
    wall = time.time() - t0
    if proc.returncode != 0:
        record(name, "COULD-NOT-RUN",
               f"tools/loss.py --pss exit {proc.returncode}: {(proc.stdout+proc.stderr)[-800:]}")
        return
    summ_path = os.path.join(outdir, "summary.json")
    if not os.path.exists(summ_path):
        record(name, "COULD-NOT-RUN", "exit 0 but no summary.json")
        return
    with open(summ_path) as f:
        summ = json.load(f)
    eff_pct = summ["efficiency"] * 100.0
    residual_pct = abs(summ["residual_pct_of_pin"])
    diff = eff_pct - cfg["tran_eff_pct"]
    detail = (f"PSS-orbit efficiency={eff_pct:.4f}% vs .tran-window {cfg['tran_eff_pct']}% "
               f"(diff {diff:+.4f} pct pts), |residual|={residual_pct:.4f}% of Pin, wall={wall:.1f}s")
    ok = abs(diff) <= 1.0 and residual_pct <= 0.5
    record(name, "pass" if ok else "FAIL", detail)


