def _r8_orbit_metrics(pss_txt, tran_txt):
    """R8 (free-running, trigger=cx rise through 1.7055 V): emitted .pss orbit vs the last periods of the settled .tran of the SAME
    tolerance.  Returns (period rel. error, {col: (max |d| % of ripple, mean offset % of ripple)}).  Orbit and reference are compared
    in the normalised phase u = t/T from the trigger crossing (column order of both files: t vout q il cx)."""
    P = wr(pss_txt, 100)
    R = wr(tran_txt, 1000)
    rt = [r[0] for r in R]
    cx = crossings(R, 4, 1.7055, rt[0], rt[-1], True)
    if len(cx) < 5:
        raise CouldNotRun("settled tran has fewer than 5 cx crossings")
    pers = [b - a for a, b in zip(cx, cx[1:])]
    Tref = sum(pers) / len(pers)
    t0, t1 = cx[-2], cx[-1]
    Tlast = t1 - t0
    pt = [0.0] + [r[0] for r in P]
    Tp = pt[-1]
    out = {}
    for c, nm in ((1, "vout"), (3, "il"), (4, "cx")):
        pv = [P[0][c]] + [r[c] for r in P]
        rv = [r[c] for r in R]
        N = 2000
        rp = [interp(rt, rv, t0 + Tlast * j / N) for j in range(N + 1)]
        pp = [interp(pt, pv, Tp * j / N) for j in range(N + 1)]
        rip = max(rp) - min(rp)
        d = [a - b for a, b in zip(pp, rp)]
        out[nm] = (100 * max(abs(x) for x in d) / rip, 100 * (sum(d[:-1]) / N) / rip)
    return (Tp - Tref) / Tref, out


