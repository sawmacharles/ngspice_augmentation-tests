def check_threads():
    """4. OpenMP determinism: BSIM4 load with num_threads 1 vs 8 must give a byte-identical wrdata (measured identical for
    the 150 us default-tolerance tran and for the pss orbit incl. iteration count and residual)."""
    md = {}
