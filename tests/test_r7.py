def pss_info(txt):
    m = re.search(r"PSS-SHOOT: CONVERGED iter=(\d+) residual=(\S+) spectral_radius=(\S+) (\S+) wall_time=(\S+)s", txt)
    if not m:
        return None
    return dict(iter=int(m.group(1)), res=float(m.group(2)), rho=float(m.group(3)), verdict=m.group(4), wall=float(m.group(5)))


def orbit_vs(A, B, cols, tmin=50e-9, n=2000):
    """max |A-B| over t>=tmin as % of A's peak-to-peak, per column (B interpolated onto A's n-point grid)."""
    tb = [r[0] for r in B]
    out = {}
    for c in cols:
        vb = [r[c] for r in B]
        pp = max(r[c] for r in A) - min(r[c] for r in A)
        out[c] = 100 * max(abs(interp(tb, vb, j * T / n) - A_at(A, j * T / n, c)) for j in range(n) if j * T / n >= tmin) / pp
    return out


def A_at(A, t, c):
    ta = [r[0] for r in A]
    return interp(ta, [r[c] for r in A], t)


def uniform_mean(rows, c, n=2000):
    ts = [r[0] for r in rows]
    vs = [r[c] for r in rows]
    return sum(interp(ts, vs, j * T / n) for j in range(n)) / n


