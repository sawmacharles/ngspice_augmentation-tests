def _pstb_vs_fra(txtfile, freqs=(20000.0, 40000.0, 80000.0, 200000.0)):
    """|T| of a `.pstb` output file (wrdata t, lin 10 20k..200k) against the converged R7 loop FRA: [(f, dB diff, FRA unc)]."""
    rows = wr(txtfile)
    out = []
    for r in rows:
        f = r[0]
