def wr(path, minrows=10):
    if not os.path.exists(path):
        raise CouldNotRun(f"missing {path}")
    rows = []
    for l in open(path):
        try:
            rows.append([float(x) for x in l.split()])
        except ValueError:
            pass
    if len(rows) < minrows:
        raise CouldNotRun(f"{path}: too few rows")
    return rows


def interp(ts, vs, t):
    import bisect
    i = bisect.bisect_left(ts, t)
    if i <= 0:
        return vs[0]
    if i >= len(ts):
        return vs[-1]
    a = (t - ts[i - 1]) / (ts[i] - ts[i - 1])
    return vs[i - 1] + a * (vs[i] - vs[i - 1])


def crossings(rows, col, lvl, t0, t1, rising):
    out, prev = [], None
    for x in rows:
        if t0 <= x[0] <= t1 and prev is not None:
            a, b = prev[col], x[col]
            if (rising and a < lvl <= b) or ((not rising) and a > lvl >= b):
                out.append(prev[0] + (x[0] - prev[0]) * (lvl - a) / (b - a))
        prev = x
    return out


# wrdata column order in every r7 fixture: t vout opout sw il ghs gls pwm
