def check_tran():
    """1. settled tran (reltol 1e-5): Vout, ripple, il, periodicity, fsw, dead time. Reference numbers measured 2026-10-01
    (s88): Vout 1.459397 V (agrees to 1e-6 between reltol 1e-4/1e-5 and tmax 1n/0.5n), ripple 70.15 mV, il 1.9464 A pp 0.970,
    periodic to <1e-5 of ripple, dead time 18.76/18.84 ns."""
    global tran
    txt, w = run("r7_tran.cir")
    rows = wr(os.path.join(OUT, "tran.txt"))
    tran = rows
    n = int(round(T / 1e-9))
    last = rows[-n:]
    prev = rows[-2 * n:-n]
    vo = [r[C_VOUT] for r in last]
    mean, pp = sum(vo) / n, max(vo) - min(vo)
    il = sum(r[C_IL] for r in last) / n
    per = max(abs(a[C_VOUT] - b[C_VOUT]) for a, b in zip(last, prev)) / pp
    t1 = rows[-1][0]
    rise = crossings(rows, C_PWM, 2.5, t1 - 10 * T, t1, True)
    fsw = (len(rise) - 1) / (rise[-1] - rise[0]) if len(rise) > 2 else float("nan")
    hs_off = crossings(rows, C_GHS, 2.5, t1 - 5 * T, t1, True)
    ls_on = crossings(rows, C_GLS, 2.5, t1 - 5 * T, t1, True)
    ls_off = crossings(rows, C_GLS, 2.5, t1 - 5 * T, t1, False)
    hs_on = crossings(rows, C_GHS, 2.5, t1 - 5 * T, t1, False)
    nxt = lambda x, L: min((y for y in L if y > x), default=None)
    d1 = [(nxt(x, ls_on) - x) * 1e9 for x in hs_off if nxt(x, ls_on) is not None]
    d2 = [(nxt(x, hs_on) - x) * 1e9 for x in ls_off if nxt(x, hs_on) is not None]
    ok = (abs(mean - 1.4594) < 5e-3 and 0.064 < pp < 0.076 and abs(il - 1.9464) < 0.02 and per < 1e-4 and abs(fsw - 500e3) < 250
          and d1 and d2 and min(d1 + d2) > 12 and max(d1 + d2) < 26)
    record("tran steady state (reltol 1e-5)", "pass" if ok else "FAIL",
           f"Vout {mean:.5f} V (ref 1.4594 +-5 mV), ripple {pp*1e3:.2f} mV (70.15 +-6), il {il:.4f} A, last-vs-previous period "
           f"{per:.1e} of ripple (<1e-4), fsw {fsw/1e3:.3f} kHz, dead time HS-off->LS-on {d1} ns, LS-off->HS-on {d2} ns "
           f"(both 12..26, i.e. never overlapping), wall {w:.0f}s")


