#!/usr/bin/env python3
"""bench/campaign_pvt_r3d.py -- a 36-point PVT campaign on the R3d
voltage-mode buck with dead-time (card #491, plan T9.6, transient-
ACCELERATION round 6), for `tools/campaign.py`.

Base circuit: `refs/r3d_vm_buck_deadtime.cir` (card #479) -- the power
stage, dead-time steering network and body/freewheel diode are copied
verbatim (same component values, same tanh-based smooth switches, same
kswd/kc/rdt/rdisch tuning that deck's own header derives and measures);
the loop-gain probe (`.include ../stb/lgprobe.lib`, `XP fbtop vout lgprobe`)
is dropped and `Ra` ties directly to `vout` instead -- the same
simplification `bench/gen_pvt.py` already makes for its own PVT deck (the
probe is for FRA/loop-gain work, out of scope for a wall-clock/memory
campaign, and dropping it avoids a `bench/`-vs-`refs/`-depth `.include`
path problem). The `write .../.raw` / `wrdata` lines are dropped too (round
1's own finding: ASCII raw-file writes are a real, avoidable cost; this
campaign never plots waveforms, so it never pays it -- see
research/transient-acceleration.md section 11).

Grid: 3 temperatures (per refs/r3d's own MEASURED section headroom, -20/25/
85 C) x 3 line voltages (10/12/14 V, R3d's own vin_v=12 nominal) x 4 loads
(1.5/3.3/6.6/10 Ohm, R3d's own rload=3.3 nominal) = 36 points -- inside the
build task's requested 30-50.

Every point keeps R3d's own full `.tran 2n 1.5m 0 uic` (no shortening --
measured single-run cost is ~8s on the fork build, see the campaign's own
report; 36 points is ~5 minutes naive-serial, tractable without trimming
the deck the way `bench/gen_pvt.py`'s own campaign trims `refs/r3_vm_buck.cir`
to 300us).

Measures (all plain `.meas tran`, no `let`-derived vectors -- avoids the
per-point `let`-vector-naming complexity a loop-mode campaign would need):
  t_period      -- one full switching period near the end of the run
  duty_final    -- AVG(v(pwm)) over the same final-period window
  vout_avg_final-- AVG(v(vout)) over the final 10us
  vout_ripple   -- PP(v(vout)) over the final 10us
"""
import itertools
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent

NGSPICE_DEFAULT = None  # caller supplies --ngspice
TIMEOUT = 120

MEASURES = ["t_period", "duty_final", "vout_avg_final", "vout_ripple"]

BODY = """\
.param vin_v={vin_v} fs=500k tclk={{1/fs}}
.param lval=10u rdcr=10m cval=100u esrval=10m rload={rload}
.param ra=2300 rb=1000 vref=1
.param r1=10k r2=27.51k r3=101.7 c1=36.35p c2=2.299n c3=6.261n
.param vramp=2
.param gm_oa=1000 ro_oa=100 co_oa=100p
.param gon=70 goff=1e-6 kc=100
.param rdt=430 rdisch=60 cdt=100p kswd=150
.param vfbody=0.6 gbody=50 kbody=50

Vin vin 0 DC {{vin_v}}

Bhs vin sw I = (V(vin)-V(sw)) * ({{goff}}+({{gon}}-{{goff}})*0.5*(1+tanh({{kswd}}*(V(dly_hs)-0.5))))
Bls sw 0   I = V(sw)              * ({{goff}}+({{gon}}-{{goff}})*0.5*(1+tanh({{kswd}}*(V(dly_ls)-0.5))))
Bbody 0 sw I = {{gbody}}*(-V(sw)-{{vfbody}})*0.5*(1+tanh({{kbody}}*(-V(sw)-{{vfbody}})))

Csw sw 0 100p
L1 sw swl {{lval}} IC=0
Rdcr swl vout {{rdcr}}
Resr vout cx {{esrval}}
Cout cx 0 {{cval}} IC=0
Rload vout 0 {{rload}}

Ra vout fbnode {{ra}}
Rb fbnode 0 {{rb}}

Vrefsrc vrefnode 0 DC {{vref}}
Goa opout 0 vrefnode compin {{gm_oa}}
Roa opout 0 {{ro_oa}}
Coa opout 0 {{co_oa}}

R1in fbnode compin {{r1}}
R3in fbnode n3 {{r3}}
C3in n3 compin {{c3}}
C1f compin opout {{c1}}
R2f compin n2 {{r2}}
C2f n2 opout {{c2}}

Vramp ramp 0 PULSE(0 {{vramp}} 0 {{0.97*tclk}} {{0.03*tclk}} 1n {{tclk}})
Bcmp pwm 0 V = 0.5*(1+tanh({{kc}}*(V(opout)-V(ramp))))

Bpwminv pwm_inv 0 V = 1-V(pwm)

.model ddt D(IS=1e-6 N=1.0)

Rchg_hs pwm dly_hs {{rdt}}
Ddis_hs dly_hs dis_hs ddt
Rdis_hs dis_hs pwm {{rdisch}}
Cdly_hs dly_hs 0 {{cdt}} IC=0

Rchg_ls pwm_inv dly_ls {{rdt}}
Ddis_ls dly_ls dis_ls ddt
Rdis_ls dis_ls pwm_inv {{rdisch}}
Cdly_ls dly_ls 0 {{cdt}} IC=0
"""

HEADER = """\
* campaign_pvt_r3d point {idx:03d}/{ntotal} -- vin_v={vin_v} rload={rload} temp={temp}
* (ngspice_augmentation card #491, plan T9.6, transient-ACCELERATION round
* 6; generated by bench/campaign_pvt_r3d.py -- do not hand-edit, regenerate
* instead). Power stage/dead-time network as refs/r3d_vm_buck_deadtime.cir
* (card #479); loop-gain probe dropped, same simplification as
* bench/gen_pvt.py's own PVT deck.
"""

TRAN_TAIL_A = """
.temp {temp}
.tran 2n 1.5m 0 uic
.control
set filetype=ascii
run
meas tran t_period TRIG v(pwm) VAL=0.5 RISE=250 TARG v(pwm) VAL=0.5 RISE=251
meas tran duty_final AVG v(pwm) FROM=1498u TO=1500u
meas tran vout_avg_final AVG v(vout) FROM=1490u TO=1500u
meas tran vout_ripple PP v(vout) FROM=1490u TO=1500u
print t_period duty_final vout_avg_final vout_ripple
.endc
.end
"""


def point_grid():
    temps = [-20, 25, 85]
    vins = [10, 12, 14]
    rloads = [1.5, 3.3, 6.6, 10.0]
    pts = []
    for temp, vin_v, rload in itertools.product(temps, vins, rloads):
        pts.append({"temp": temp, "vin_v": vin_v, "rload": rload})
    return pts


POINTS = point_grid()
assert 30 <= len(POINTS) <= 50, len(POINTS)


def build_point_deck(point, idx):
    header = HEADER.format(idx=idx, ntotal=len(POINTS), **point)
    body = BODY.format(vin_v=point["vin_v"], rload=point["rload"])
    tail = TRAN_TAIL_A.format(temp=point["temp"])
    return header + body + tail


# --------------------------------------------------------------------- #
# Mode (b): single-process loop
# --------------------------------------------------------------------- #

def build_loop_prelude(points):
    p0 = points[0]
    header = """\
* campaign_pvt_r3d.py -- single-process loop form (36 points, one ngspice
* session, alterparam vin_v/rload + option temp + reset + run + meas per
* point -- the mode-(b) counterpart of the per-point decks
* build_point_deck() writes; see that function's docstring for the base
* circuit). Generated, not hand-edited.
"""
    body = BODY.format(vin_v=p0["vin_v"], rload=p0["rload"])
    ctrl_head = """
.tran 2n 1.5m 0 uic
.options reltol=1e-3
.control
set filetype=ascii
rusage cputime
"""
    return header + body + ctrl_head


def build_loop_entry(point, idx):
    return f"""
* --- point {idx:03d}: vin_v={point['vin_v']} rload={point['rload']} temp={point['temp']} ---
alterparam vin_v = {point['vin_v']}
alterparam rload = {point['rload']}
option temp = {point['temp']}
reset
run
meas tran p{idx:03d}_t_period TRIG v(pwm) VAL=0.5 RISE=250 TARG v(pwm) VAL=0.5 RISE=251
meas tran p{idx:03d}_duty_final AVG v(pwm) FROM=1498u TO=1500u
meas tran p{idx:03d}_vout_avg_final AVG v(vout) FROM=1490u TO=1500u
meas tran p{idx:03d}_vout_ripple PP v(vout) FROM=1490u TO=1500u
print p{idx:03d}_t_period p{idx:03d}_duty_final p{idx:03d}_vout_avg_final p{idx:03d}_vout_ripple
"""


def build_loop_tail():
    return "\nrusage cputime\nquit\n.endc\n.end\n"


if __name__ == "__main__":
    print(f"{len(POINTS)} points")
    print(build_point_deck(POINTS[0], 0))
