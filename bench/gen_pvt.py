#!/usr/bin/env python3
"""gen_pvt.py -- generate bench task 1c (ngspice_augmentation card #467, plan
T9.1): a 50-point PVT campaign of a smaller buck deck, in two forms:

 - bench/decks/pvt_points/pt_NN.cir  (50 separate netlists, one per process)
 - bench/decks/c_pvt_loop.cir        (one ngspice session, 50 points via
   alterparam+reset+tran+meas in a single .control block)

Both use the same 50-point grid: 5 "process" points (gon_scale, a synthetic
stand-in for switch-Ron process spread -- this deck has no real semiconductor
model, see a_pex_buck.cir for that) x 5 voltage points (vin_v) x 2 temperature
points (.temp) = 50, deliberately chosen to factor evenly.

The base circuit is refs/r3_vm_buck.cir's power stage / type-III compensator
/ PWM comparator, trimmed to a much shorter transient (--tstop-us, default
300us vs r3's 1.5ms) so 50 points finish in a tractable time, and with the
loop-gain probe (refs/... XP/lgprobe.lib) dropped (not needed for a
wall-clock benchmark, and it would add a relative .include dependency to
every generated point file).
"""
import argparse
import itertools
import pathlib

HERE = pathlib.Path(__file__).resolve().parent

BODY = """\
.param vin_v={vin_v} gon_scale={gon_scale}
.temp {temp}
.param fs=500k tclk={{1/fs}}
.param lval=10u rdcr=10m cval=100u esrval=10m rload=3.3
.param ra=2300 rb=1000 vref=1
.param r1=10k r2=27.51k r3=101.7 c1=36.35p c2=2.299n c3=6.261n
.param vramp=2
.param gm_oa=1000 ro_oa=100 co_oa=100p
.param gon=100 goff=1e-6 ksw=30 kc=30

Vin vin 0 DC {{vin_v}}

Bhs vin sw I = (V(vin)-V(sw)) * ({{goff}}+({{gon}}*{{gon_scale}}-{{goff}})*0.5*(1+tanh({{ksw}}*(V(pwm)-0.5))))
Bls sw 0   I = V(sw)              * ({{goff}}+({{gon}}*{{gon_scale}}-{{goff}})*0.5*(1+tanh({{ksw}}*(0.5-V(pwm)))))

Csw sw 0 100p
L1 sw swl {{lval}} IC=0
Rdcr swl vout {{rdcr}}
Resr vout cx {{esrval}}
Cout cx 0 {{cval}} IC=0
Rload vout 0 {{rload}}

Ra vout fbnode {{ra}}
Rb fbnode 0 {{rb}}

Vrefsrc vrefnode 0 DC {{vref}}
Goa opout 0 vrefnode compin {{gm_oa}}
Roa opout 0 {{ro_oa}}
Coa opout 0 {{co_oa}}

R1in fbnode compin {{r1}}
R3in fbnode n3 {{r3}}
C3in n3 compin {{c3}}
C1f compin opout {{c1}}
R2f compin n2 {{r2}}
C2f n2 opout {{c2}}

Vramp ramp 0 PULSE(0 {{vramp}} 0 {{0.97*tclk}} {{0.03*tclk}} 1n {{tclk}})
Bcmp pwm 0 V = 0.5*(1+tanh({{kc}}*(V(opout)-V(ramp))))
"""

HEADER = """\
* c_pvt_base point {idx:03d}/{ntotal} -- vin_v={vin_v} gon_scale={gon_scale} temp={temp}
* (ngspice_augmentation card #467, plan T9.1, bench task 1c; generated by
* bench/gen_pvt.py -- do not hand-edit, regenerate instead). Power
* stage/compensator as refs/r3_vm_buck.cir (see that file for the design
* derivation), trimmed to {tstop_us}us and with the loop-gain probe dropped.
"""

MEAS_SEPARATE = """
.tran {tstep} {tstop_us}u 0 uic
.options reltol=1e-3

.control
set filetype=ascii
run
meas tran vout_avg_final AVG v(vout) FROM={t_from}u TO={tstop_us}u
meas tran vout_max_final MAX v(vout) FROM={t_from}u TO={tstop_us}u
meas tran vout_min_final MIN v(vout) FROM={t_from}u TO={tstop_us}u
let vout_ripple = vout_max_final - vout_min_final
meas tran wave_mid find v(vout) at={t_mid}u
meas tran wave_end find v(vout) at={tstop_us}u
print vout_avg_final vout_max_final vout_min_final vout_ripple wave_mid wave_end
.endc
.end
"""


def point_grid():
    gon_scales = [0.7, 0.85, 1.0, 1.15, 1.3]
    vins = [10, 11, 12, 13, 14]
    temps = [0, 85]
    pts = []
    for temp, vin_v, gon_scale in itertools.product(temps, vins, gon_scales):
        pts.append(dict(temp=temp, vin_v=vin_v, gon_scale=gon_scale))
    return pts


def gen_separate(pts, tstop_us, tstep, outdir):
    outdir = pathlib.Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    t_from = tstop_us * 0.9667  # last ~10us of a 300us run, scaled
    t_mid = tstop_us * 0.5
    for i, pt in enumerate(pts):
        header = HEADER.format(idx=i, ntotal=len(pts), tstop_us=tstop_us, **pt)
        body = BODY.format(**pt)
        meas = MEAS_SEPARATE.format(tstep=tstep, tstop_us=tstop_us, t_from=t_from, t_mid=t_mid)
        (outdir / f"pt_{i:03d}.cir").write_text(header + body + meas)
    print(f"wrote {len(pts)} point files under {outdir}")


def gen_loop(pts, tstop_us, tstep, outpath):
    t_from = tstop_us * 0.9667
    t_mid = tstop_us * 0.5
    lines = [f"""\
* c_pvt_loop -- single-process 50-point PVT campaign (ngspice_augmentation
* card #467, plan T9.1, bench task 1c; generated by bench/gen_pvt.py -- do
* not hand-edit, regenerate instead). Same 50-point grid and same base
* circuit as bench/decks/pvt_points/pt_NN.cir (the separate-process form of
* this benchmark), run instead as one ngspice session: 'alterparam' each
* .param, 'reset' to re-elaborate, 'tran' again, per point -- this is the
* other half of the (a) many-short-points vs single-process-loop comparison
* the archived ngspice_accel project's S-A work made for parse/setup cost
* (see research/transient-acceleration.md).
"""]
    lines.append(BODY.format(vin_v=pts[0]["vin_v"], gon_scale=pts[0]["gon_scale"], temp=pts[0]["temp"]))
    lines.append(f"\n.tran {tstep} {tstop_us}u 0 uic\n.options reltol=1e-3\n\n.control\nset filetype=ascii\nrusage cputime\n")
    for i, pt in enumerate(pts):
        lines.append(f"\n* --- point {i:03d}: vin_v={pt['vin_v']} gon_scale={pt['gon_scale']} temp={pt['temp']} ---\n")
        lines.append(f"alterparam vin_v = {pt['vin_v']}\n")
        lines.append(f"alterparam gon_scale = {pt['gon_scale']}\n")
        lines.append(f"option temp = {pt['temp']}\n")
        lines.append("reset\n")
        lines.append("run\n")
        lines.append(f"meas tran p{i:03d}_vout_avg AVG v(vout) FROM={t_from}u TO={tstop_us}u\n")
        lines.append(f"meas tran p{i:03d}_vout_ripple PP v(vout) FROM={t_from}u TO={tstop_us}u\n")
        lines.append(f"meas tran p{i:03d}_wave_mid find v(vout) at={t_mid}u\n")
        lines.append(f"meas tran p{i:03d}_wave_end find v(vout) at={tstop_us}u\n")
    lines.append("\nrusage cputime\nquit\n.endc\n.end\n")
    pathlib.Path(outpath).write_text("".join(lines))
    print(f"wrote {outpath} ({len(pts)} points, single process)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tstop-us", type=float, default=300.0)
    ap.add_argument("--tstep", default="20n")
    ap.add_argument("--outdir-separate", default=str(HERE / "decks" / "pvt_points"))
    ap.add_argument("--out-loop", default=str(HERE / "decks" / "c_pvt_loop.cir"))
    args = ap.parse_args()

    pts = point_grid()
    assert len(pts) == 50, len(pts)
    gen_separate(pts, args.tstop_us, args.tstep, args.outdir_separate)
    gen_loop(pts, args.tstop_us, args.tstep, args.out_loop)


if __name__ == "__main__":
    main()
