#!/usr/bin/env python3
"""bench/campaign_mc_diffpair.py -- a 200-run Monte Carlo campaign on a
differential-pair input-offset example (card #491, plan T9.6, transient-
ACCELERATION round 6), for `tools/campaign.py`.

Circuit: the same 5T-style NMOS differential pair as
`docs/examples/mc_diffpair_offset.cir` (card #473) -- `nch4` model card,
resistive loads, 100uA tail, Pelgrom-scaled input-referred offset -- copied
here as a `.param`-driven BODY (not the original `@@TOKEN@@` template file
itself, and not editing that file) so BOTH campaign modes (one-process-per-
point via a literal substitution, and a single-process `alterparam` loop)
can share one circuit definition. `w=8u l=1u`, matching the W,L docs/mc.md's
own worked example used for its Pelgrom-vs-measured-MC agreement table
(1.1% agreement at this size) -- same coefficient (`A=4mV*um`, itself a
made-up, clearly-synthetic number per that document, not a real process's
characterised mismatch).

Sampling reuses `tools/mc.py`'s own scheme directly (`sample_param`,
`_seed_int`/`_rng_for` -- hash-derived per (seed, run_idx, param-name)
streams, no core-numparam random-function dependency, per that module's own
"why this exists" writeup: an in-deck `.param = agauss(...)` is
re-evaluated per *use*, not bound once (card #473's finding); every value
here is sampled once in Python and pushed in as a plain literal (mode a) or
via `alterparam` (mode b) -- never an in-deck random function -- so that
finding does not apply to either mode here.

Measures use `tools/mc.py`'s own `MCMEAS name=value` tagged-print
convention (`.meas` is not reliable for a bare `.op}` analysis -- the same
reason that file's own `.control` block uses `let`/`set`/`echo MCMEAS`
instead), extended here with the `pNNN_` prefix `tools/campaign.py`'s
loop-mode parser expects (`MCMEAS pNNN_name=value`).
"""
import os
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "tools"))
import mc  # noqa: E402  -- reuse tools/mc.py's sampling scheme

NGSPICE_DEFAULT = None
TIMEOUT = 30

SEED = 473200  # card #473 (mc.py's own card) + this campaign's N, arbitrary but fixed/documented
N = 200
MW = 8.0
ML = 1.0
PELGROM = {"coeff": 4e-3, "w": MW, "l": ML}  # V*um / sqrt(um^2) -> V, docs/mc.md's own worked-example A

VOFF_PARAM = {"name": "voff", "scope": "local", "dist": "gauss", "nominal": 0.0, "pelgrom": PELGROM}

MEASURES = ["vdiff"]

BODY = """\
.param vdd_v=3.3 vcm=1.0 mw={mw} ml={ml} voff={voff:.10g}

.model nch4 nmos level=54 version=4.8.2
+ mobmod=0 capmod=0 igcmod=0 igbmod=0 rdsmod=0 rbodymod=0 rgatemod=0 acnqsmod=0
+ toxe=3e-9 toxp=3e-9 toxm=3e-9
+ vth0=0.5 k1=0.4 k2=0 k3=0 w0=2.5e-6
+ u0=300 vsat=1.1e5
+ cgso=2e-10 cgdo=2e-10 cgbo=0 cgsl=0 cgdl=0
+ cf=0 cjs=1e-4 cjd=1e-4 cjswd=1e-10 cjswgd=1e-10

Vdd vdd 0 DC {{vdd_v}}
R1 vdd out1 10k
R2 vdd out2 10k
M1 out1 inp tail 0 nch4 w={{mw*1u}} l={{ml*1u}}
M2 out2 intn tail 0 nch4 w={{mw*1u}} l={{ml*1u}}
Itail tail 0 DC 100u
Vinp inp 0 DC {{vcm}}
Vcmn intn0 0 DC {{vcm}}
Voff intn intn0 DC {{voff}}
"""

HEADER = """\
* campaign_mc_diffpair point {idx:03d}/{ntotal} -- voff={voff:.6g}
* (ngspice_augmentation card #491, plan T9.6, transient-ACCELERATION round
* 6; generated by bench/campaign_mc_diffpair.py -- do not hand-edit,
* regenerate instead). Same 5T diff-pair circuit as
* docs/examples/mc_diffpair_offset.cir (card #473), copied into a
* .param-driven form so both campaign modes can share one body. Sampling
* via tools/mc.py's own sample_param/seed scheme.
"""

TAIL_A = """
.control
op
let vd = v(out1) - v(out2)
set vds = $&vd
echo MCMEAS vdiff={vds_lit}
.endc
.end
"""


def _sample_points():
    pts = []
    for i in range(N):
        voff = mc.sample_param(VOFF_PARAM, SEED, i)
        pts.append({"voff": voff})
    return pts


POINTS = _sample_points()
assert len(POINTS) == N


def build_point_deck(point, idx):
    header = HEADER.format(idx=idx, ntotal=N, voff=point["voff"])
    body = BODY.format(mw=MW, ml=ML, voff=point["voff"])
    # `echo MCMEAS vdiff=$vds` needs $vds expanded by ngspice itself (a
    # control-mode variable), not by this Python template -- leave the
    # literal `$vds` token in place (the `{vds_lit}` name above documents
    # that this is deliberate, not a missed substitution).
    tail = TAIL_A.format(vds_lit="$vds")
    return header + body + tail


# --------------------------------------------------------------------- #
# Mode (b): single-process loop
# --------------------------------------------------------------------- #

def build_loop_prelude(points):
    p0 = points[0]
    header = """\
* campaign_mc_diffpair.py -- single-process loop form (200 MC runs, one
* ngspice session, alterparam voff + reset + op + echo MCMEAS per point --
* the mode-(b) counterpart of build_point_deck()). Generated, not
* hand-edited. voff values sampled once in Python (tools/mc.py's scheme),
* pushed in via alterparam -- never an in-deck random function, so card
* #473's "agauss re-evaluated per use" finding does not apply here.
"""
    body = BODY.format(mw=MW, ml=ML, voff=p0["voff"])
    ctrl_head = """
.control
rusage cputime
"""
    return header + body + ctrl_head


def build_loop_entry(point, idx):
    return f"""
* --- point {idx:03d}: voff={point['voff']:.10g} ---
alterparam voff = {point['voff']:.10g}
reset
op
let vd = v(out1) - v(out2)
set vds = $&vd
echo MCMEAS p{idx:03d}_vdiff=$vds
"""


def build_loop_tail():
    return "\nrusage cputime\nquit\n.endc\n.end\n"


if __name__ == "__main__":
    print(f"{len(POINTS)} points, first 3 voff: {[p['voff'] for p in POINTS[:3]]}")
    print(build_point_deck(POINTS[0], 0))
