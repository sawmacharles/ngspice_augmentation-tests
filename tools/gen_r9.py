#!/usr/bin/env python3
"""gen_r9.py -- writes refs/r9_digital_buck.cir (card #551): a digitally controlled synchronous buck built from XSPICE primitives.

    python3 tools/gen_r9.py [--nbits 11] [--div 600] [--bin 1.5e-3] [--out refs/r9_digital_buck.cir] [--tag fine]

Power stage = R3's (12 V -> 3.3 V, L 10 uH, C 100 uF, ESR 10 mOhm, Rload 3.3, smooth tanh switches), 500 kHz.  Controller, all XSPICE:
  * ADC: two adc_bridge comparators on the feedback node (fb > vref+bin, fb < vref-bin): a 3-level quantiser with a zero-error bin.
  * sampled by d_dff on the falling clock edge; slow enable clock = d_fdiv(clk / div);
  * digital integrator: synchronous up/down counter (nbits d_tff + d_and/d_or carry logic), steps +-1 LSB every `div` clocks while the
    sampled error is outside the bin;
  * DPWM: dac_bridge (multi-bit -> analog code) -> d_pwm (duty = 0.01 + 0.98*code) -> dac_bridge -> smooth switch drive.
The no-limit-cycle condition (Peterchev/Sanders): the DPWM step in output volts is smaller than the ADC zero-error bin.
  nbits 11: 1 LSB = 0.98/2048*12 V = 5.7 mV at Vout (1.7 mV at fb)  < bin width 3 mV at fb  -> settles to a fixed code.
  nbits 7 : 1 LSB = 92 mV at Vout (28 mV at fb) >> bin -> the integrator hunts +-1 LSB: a digital limit cycle (period 2 steps).
"""
import argparse
ap = argparse.ArgumentParser()
ap.add_argument("--nbits", type=int, default=11)
ap.add_argument("--div", type=int, default=600)
ap.add_argument("--bin", type=float, default=3e-3)
ap.add_argument("--out", default="refs/r9_digital_buck.cir")
ap.add_argument("--init", type=float, default=0.2745, help="initial duty (ic of the counter)")
ap.add_argument("--inject", action="store_true", help="add a summer + Vinj (DC 0) in the DPWM control path: control-to-output FRA/PAC injection point")
ap.add_argument("--lgprobe", default="../stb/lgprobe.lib", help="include path of the loop-gain probe subcircuit (relative to the deck)")
ap.add_argument("--control", default=None, help="analysis block appended before .end (default: a 60 ms settled tran, outputs under ~/Work/data)")
a = ap.parse_args()
nb, M = a.nbits, a.div
code0 = int(round((a.init - 0.01) / 0.98 * 2 ** nb))
bits = [(code0 >> i) & 1 for i in range(nb)]
L = []
w = L.append
w("* R9 digitally controlled synchronous buck from XSPICE primitives (ngspice_augmentation, card #551, 2026-10-02) -- GENERATED by tools/gen_r9.py")
w("* nbits=%d div=%d bin=%g (fb volts) initial duty %.4f (code %d)" % (nb, M, a.bin, a.init, code0))
w(".param vin_v=12 fs=500k tclk={1/fs}")
w(".param lval=10u rdcr=10m cval=100u esrval=10m rload=3.3 ra=2300 rb=1000 vref=1 bin=%g" % a.bin)
w(".param gon=100 goff=1e-6 ksw=30")
w("Vin vin 0 DC {vin_v}")
w("* power stage (R3): smooth switches driven by the DPWM node pwm (0/1 V)")
w("Bhs vin sw I = (V(vin)-V(sw)) * ({goff}+({gon}-{goff})*0.5*(1+tanh({ksw}*(V(pwm)-0.5))))")
w("Bls sw 0 I = V(sw) * ({goff}+({gon}-{goff})*0.5*(1+tanh({ksw}*(0.5-V(pwm)))))")
w("Csw sw 0 100p\nL1 sw swl {lval} IC=0\nRdcr swl vout {rdcr}\nResr vout cx {esrval}\nCout cx 0 {cval} IC=0\nRload vout 0 {rload}")
w(".include %s\nXP" % a.lgprobe + " fbtop vout lgprobe\nRa fbtop fbnode {ra}\nRb fbnode 0 {rb}")
w("* clock: native source -> digital clock; falling-edge sampling clock")
w("Vclk clk 0 PULSE(0 1 0 5n 5n {0.5*tclk-5n} {tclk})\nVone one 0 DC 1\nVzero zero 0 DC 0")
w("Abr [clk one zero] [dclk dhi dlo] adcclk\n.model adcclk adc_bridge(in_low=0.3 in_high=0.7 rise_delay=1n fall_delay=1n)")
w("Ainv dclk dclkn minv\n.model minv d_inverter(rise_delay=1n fall_delay=1n)")
w("* ADC: zero-error-bin comparators on the feedback node")
w("Ehi ehi 0 value = {V(fbnode)-vref-bin}\nElo elo 0 value = {vref-bin-V(fbnode)}")
w("Aadc [ehi elo] [chi clo] adccmp\n.model adccmp adc_bridge(in_low=-0.2u in_high=0.2u rise_delay=1n fall_delay=1n)")
w("Adh chi dclkn dlo dlo shi shin mdf\nAdl clo dclkn dlo dlo slo slon mdf\n.model mdf d_dff(clk_delay=2n set_delay=1n reset_delay=1n ic=0)")
w("* slow enable clock")
w("Afd dclk dslow mfd\n.model mfd d_fdiv(div_factor=%d high_cycles=%d i_count=0 rise_delay=2n fall_delay=2n)" % (M, M // 2))
w("* up/down counter: lo -> count up, hi -> count down")
w("Aen [shi slo] en mor\n.model mor d_or(rise_delay=1n fall_delay=1n)\n.model mand d_and(rise_delay=1n fall_delay=1n)\n.model mbuf d_buffer(rise_delay=1n fall_delay=1n)")
for i in range(nb):
    w("Atf%d t%d dslow dlo dlo b%d bn%d mtf%d\n.model mtf%d d_tff(clk_delay=2n set_delay=1n reset_delay=1n ic=%d)" % (i, i, i, i, i, i, bits[i]))
w("* T0 = en;  T_i = lo & AND(b_0..b_i-1)  |  hi & AND(~b_0..~b_i-1)")
w("Ab0 en t0 mbuf")
for i in range(1, nb):
    up_in = " ".join("b%d" % j for j in range(i))
    dn_in = " ".join("bn%d" % j for j in range(i))
    if i == 1:
        w("Acu%d b0 cu%d mbuf\nAcd%d bn0 cd%d mbuf" % (i, i, i, i))
    else:
        w("Acu%d [%s] cu%d mand\nAcd%d [%s] cd%d mand" % (i, up_in, i, i, dn_in, i))
    w("Atu%d [slo cu%d] tu%d mand\nAtd%d [shi cd%d] td%d mand\nAto%d [tu%d td%d] t%d mor" % (i, i, i, i, i, i, i, i, i, i))
w("* DPWM: code -> analog (0..1) -> d_pwm -> drive node")
w("Adac [%s] [code] dacm\n.model dacm dac_bridge(out_low=0 out_high=1 t_rise=1n t_fall=1n)" % " ".join("b%d" % i for i in reversed(range(nb))))   # dac_bridge: in[0] is the MSB
if a.inject:
    w("Vinj vinj 0 DC 0\nAsumc [code vinj] ctl msum\n.model msum summer(in_gain=[1 1] out_gain=1)")
    cname = "ctl"
else:
    cname = "code"
w("Apwm %s dpw mpwm\n.model mpwm d_pwm(cntl_array=[0 1] dc_array=[0.01 0.99] frequency={fs} init_phase=0 rise_delay=1n fall_delay=1n)" % cname)
w("Adrv [dpw] [pwm] dacd\n.model dacd dac_bridge(out_low=0 out_high=1 t_rise=5n t_fall=5n)")
w("Rpw pwm 0 1Meg")
w(".ic v(vout)=0 v(cx)=0")
DEFAULT = """.options reltol=1e-4
.control
set filetype=ascii
set wr_singlescale
set wr_vecnames
set numdgt=12
shell mkdir -p ~/Work/data/ngspice_augmentation/refs/r9_digital_buck
tran 100n 60m uic
wrdata ~/Work/data/ngspice_augmentation/refs/r9_digital_buck/r9_tran.txt v(vout) v(code) v(pwm) i(L1) v(fbnode)
meas tran vavg AVG v(vout) FROM=58.8m TO=60m
meas tran vmax MAX v(vout) FROM=58.8m TO=60m
meas tran vmin MIN v(vout) FROM=58.8m TO=60m
quit
.endc"""
w(DEFAULT if a.control is None else a.control)
w(".end")
open(a.out, "w").write("\n".join(L) + "\n")
print("wrote", a.out, "code0", code0)
